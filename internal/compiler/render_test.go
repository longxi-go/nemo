package compiler

import (
	"strings"
	"testing"
)

func TestRenderUsesSemanticFields(t *testing.T) {
	models := []preparedPackage{
		{
			model: packageModel{
				Name:  "fixture",
				Names: newGeneratedNames(newIdentifiers(nil)),
				Helpers: []helperModel{
					{
						Name: "nemoBindConfig",
						Type: "Config",
						Fields: []fieldModel{
							{
								Name:       "Port",
								Key:        "port",
								Mode:       "read",
								Reader:     "binding.Read",
								HasDefault: true,
								Default:    "8080",
								Decoder:    "binding.Signed[int]",
							},
						},
					},
				},
			},
		},
	}
	outputs, err := renderModels(models)
	if err != nil {
		t.Fatal(err)
	}
	text := string(outputs[0].Content)
	for _, fragment := range []string{"// Code generated by nemoctl. DO NOT EDIT.", "func nemoBindConfig(", "next.Port = value", "HasDefault: true", "Default: \"8080\"", "binding.Signed[int]"} {
		if !strings.Contains(text, fragment) {
			t.Fatalf("missing %q in %s", fragment, text)
		}
	}
}

// An unknown mode must fail before it can select an unrelated object branch.
func TestRenderRejectsUnknownFieldMode(t *testing.T) {
	for _, mode := range []string{"", "unknown"} {
		models := []preparedPackage{
			{
				model: packageModel{
					Name: "fixture",
					Helpers: []helperModel{
						{
							Name: "nemoBindConfig",
							Type: "Config",
							Fields: []fieldModel{
								{
									Name: "Port",
									Mode: fieldMode(mode),
								},
							},
						},
					},
				},
			},
		}
		outputs, err := renderModels(models)
		if err == nil || len(outputs) != 0 {
			t.Fatalf("mode %q: rendered invalid model: %d outputs, %v", mode, len(outputs), err)
		}
		if !strings.Contains(err.Error(), "Config.Port") || !strings.Contains(err.Error(), "mode") {
			t.Fatalf("mode %q: missing field diagnostic: %v", mode, err)
		}
	}
}
