func TestObsoleteAndForeignGeneratedOutput(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "go.mod"), consumerModule(t, "fixture"))
	source := filepath.Join(dir, "config.go")
	annotated := read(t, "testdata/output-ownership/config.go.tmpl")
	write(t, source, annotated)
	command(t, dir, "go", "mod", "tidy")
	options := codegen.Options{
		Dir: dir,
	}
	if _, err := codegen.Run(context.Background(), options); err != nil {
		t.Fatal(err)
	}
	generated := filepath.Join(dir, "zz_nemo.gen.go")
	before := read(t, generated)
	mod := read(t, filepath.Join(dir, "go.mod"))
	sum := read(t, filepath.Join(dir, "go.sum"))
	write(t, source, strings.ReplaceAll(annotated, "// +nemo:config:prefix=app\n", ""))
	options.Check = true
	if _, err := codegen.Run(context.Background(), options); err == nil {
		t.Fatal("obsolete methods accepted by Check")
	}
	if read(t, generated) != before {
		t.Fatal("check wrote obsolete output")
	}
	if _, err := codegen.Inspect(context.Background(), options); err != nil {
		t.Fatal(err)
	}
	if read(t, generated) != before {
		t.Fatal("inspect wrote obsolete output")
	}
	options.Check = false
	if _, err := codegen.Run(context.Background(), options); err != nil {
		t.Fatal(err)
	}
	cleaned := read(t, generated)
	if !strings.Contains(cleaned, "Code generated by nemoctl.") || strings.Contains(cleaned, "BindProperties") || strings.Contains(cleaned, "import") {
		t.Fatalf("not package-only output: %s", cleaned)
	}
	if _, err := codegen.Run(context.Background(), codegen.Options{
		Dir:   dir,
		Check: true,
	}); err != nil {
		t.Fatal(err)
	}
	if read(t, filepath.Join(dir, "go.mod")) != mod || read(t, filepath.Join(dir, "go.sum")) != sum {
		t.Fatal("module metadata changed")
	}
	// Removing metadata also removes generated methods from type validation: old callers must fail.
	write(t, source, read(t, "testdata/output-ownership/caller.go.tmpl"))
	if _, err := codegen.Run(context.Background(), options); err != nil {
		t.Fatal(err)
	}
	before = read(t, generated)
	write(t, source, strings.ReplaceAll(read(t, source), "// +nemo:config:prefix=app\n", ""))
	if _, err := codegen.Run(context.Background(), options); err == nil {
		t.Fatal("obsolete methods retained for old callers")
	}
	if read(t, generated) != before {
		t.Fatal("failed overlay changed output")
	}
	write(t, source, annotated)
	foreign := "// This file belongs to the application.\npackage fixture\nconst UserOwned = true\n"
	write(t, generated, foreign)
	for _, check := range []bool{true, false} {
		options.Check = check
		if _, err := codegen.Run(context.Background(), options); err == nil {
			t.Fatal("foreign generated filename accepted")
		}
		if read(t, generated) != foreign {
			t.Fatal("foreign file overwritten")
		}
	}
}

func TestForeignGeneratedFilePreserved(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "go.mod"), consumerModule(t, "foreign"))
	write(t, filepath.Join(dir, "config.go"), read(t, "testdata/foreign-output/config.go.tmpl"))
	command(t, dir, "go", "mod", "tidy")
	path := filepath.Join(dir, "zz_nemo.gen.go")
	foreign := "// Authored by the application.\npackage foreign\nconst Keep = true\n"
	write(t, path, foreign)
	if _, err := codegen.Run(context.Background(), codegen.Options{
		Dir: dir,
	}); err == nil {
		t.Error("foreign file overwritten")
	}
	if read(t, path) != foreign {
		t.Error("foreign source not preserved")
	}
}
